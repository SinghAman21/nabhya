import { PDFDocument, rgb, StandardFonts } from "pdf-lib";

export interface ReceiptContent {
	receiptNumber: string;
	amountMinor: number;
	currency: string;
	completedAt: Date;
	donorName: string | null;
	donorEmail: string | null;
	organizationName: string;
	organizationCity: string | null;
	organizationRegistration: string | null;
	paymentReference: string | null;
	provider: string;
}

const BRAND = rgb(1, 0.494, 0.251); // #FF7E40, the certificate's accent
const INK = rgb(0.067, 0.067, 0.067);
const MUTED = rgb(0.4, 0.4, 0.4);
const RULE = rgb(0.88, 0.88, 0.88);

/**
 * "INR 1,500.00" rather than "₹1,500". The standard PDF fonts are WinAnsi
 * encoded and have no rupee glyph - pdf-lib throws on it - and embedding a
 * font file for one character is not worth it on a receipt.
 */
export function formatReceiptAmount(amountMinor: number, currency: string) {
	const major = new Intl.NumberFormat("en-IN", {
		minimumFractionDigits: 2,
		maximumFractionDigits: 2,
	}).format(amountMinor / 100);
	return `${currency} ${major}`;
}

/**
 * Renders a donation receipt as a portrait A4 PDF.
 *
 * It is an acknowledgement of payment issued by Nabhya, and says so: Nabhya
 * collects on the NGO's behalf and holds no 80G registration of its own, so
 * the receipt must not read as a tax-exemption certificate. Like the
 * certificate PDF it is rebuilt from the database on demand, so a lost file
 * costs nothing.
 */
export async function renderReceiptPdf(
	content: ReceiptContent,
): Promise<Uint8Array> {
	const pdf = await PDFDocument.create();
	pdf.setTitle(`Donation receipt ${content.receiptNumber}`);
	pdf.setAuthor("Nabhya");

	const page = pdf.addPage([595, 842]); // A4 portrait, points
	const { width, height } = page.getSize();

	const sans = await pdf.embedFont(StandardFonts.Helvetica);
	const sansBold = await pdf.embedFont(StandardFonts.HelveticaBold);

	const left = 56;
	const right = width - 56;

	const text = (
		value: string,
		x: number,
		y: number,
		size: number,
		font = sans,
		color = INK,
	) => page.drawText(value, { x, y, size, font, color });

	const rightAlign = (
		value: string,
		y: number,
		size: number,
		font = sans,
		color = INK,
	) =>
		text(
			value,
			right - font.widthOfTextAtSize(value, size),
			y,
			size,
			font,
			color,
		);

	const rule = (y: number, color = RULE, thickness = 1) =>
		page.drawLine({
			start: { x: left, y },
			end: { x: right, y },
			color,
			thickness,
		});

	// Header.
	text("NABHYA", left, height - 72, 18, sansBold, BRAND);
	text("NGO VOLUNTEER PLATFORM", left, height - 88, 8, sans, MUTED);
	rightAlign("DONATION RECEIPT", height - 72, 12, sansBold);
	rightAlign(content.receiptNumber, height - 88, 10, sans, MUTED);
	rule(height - 104, BRAND, 1.5);

	// The amount, as the one thing the reader looks for.
	text("Amount received", left, height - 150, 10, sans, MUTED);
	text(
		formatReceiptAmount(content.amountMinor, content.currency),
		left,
		height - 184,
		30,
		sansBold,
	);
	text(
		`Paid on ${formatReceiptDate(content.completedAt)}`,
		left,
		height - 206,
		10,
		sans,
		MUTED,
	);

	// Facts table.
	const rows: Array<[string, string]> = [
		["Received from", content.donorName ?? "Donor"],
		["Donor email", content.donorEmail ?? "-"],
		[
			"In support of",
			[content.organizationName, content.organizationCity]
				.filter(Boolean)
				.join(", "),
		],
		["NGO registration", content.organizationRegistration ?? "-"],
		["Payment method", humanizeProvider(content.provider)],
		["Payment reference", content.paymentReference ?? "-"],
		["Receipt number", content.receiptNumber],
	];

	let y = height - 256;
	rule(y + 18);
	for (const [label, value] of rows) {
		text(label, left, y, 10, sans, MUTED);
		rightAlign(truncate(value, 60), y, 10, sansBold);
		rule(y - 12);
		y -= 32;
	}

	// What this document is, and is not.
	const notes = [
		"This receipt acknowledges a donation made through Nabhya to the NGO named above.",
		"It is not a tax-exemption (80G) certificate. If you need one, ask the NGO directly;",
		"only an NGO registered under section 80G of the Income Tax Act can issue it.",
	];
	let noteY = y - 24;
	for (const line of notes) {
		text(line, left, noteY, 9, sans, MUTED);
		noteY -= 14;
	}

	text(
		"Generated by Nabhya from its donation records.",
		left,
		56,
		8,
		sans,
		MUTED,
	);
	rightAlign(`Receipt ${content.receiptNumber}`, 56, 8, sans, MUTED);

	return pdf.save();
}

function formatReceiptDate(value: Date) {
	return new Intl.DateTimeFormat("en-IN", {
		day: "numeric",
		month: "long",
		year: "numeric",
		hour: "numeric",
		minute: "2-digit",
		hour12: true,
		timeZone: "Asia/Kolkata",
	}).format(value);
}

function humanizeProvider(provider: string) {
	if (provider === "razorpay") return "Razorpay";
	if (provider === "stub") return "Test payment";
	return provider;
}

/** WinAnsi cannot draw every character a name may contain; see the amount. */
function truncate(value: string, max: number) {
	const safe = value.replace(/[^\x20-\x7E -ÿ]/g, "?");
	return safe.length > max ? `${safe.slice(0, max - 1)}...` : safe;
}
