/** Rebuild the small SVG geometry without adding a map engine to the client. */
import { readFile, writeFile } from "node:fs/promises";

const source =
	"https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_admin_0_countries.geojson";
const collection = process.argv[2]
	? JSON.parse(await readFile(process.argv[2], "utf8"))
	: await (await fetch(source)).json();
const india = collection.features.find(
	(feature) => feature.properties.ADM0_A3 === "IND",
);
if (!india || india.geometry.type !== "MultiPolygon")
	throw new Error("Expected Natural Earth India multipolygon");
const mercator = (latitude) =>
	Math.log(Math.tan(Math.PI / 4 + (latitude * Math.PI) / 360));
const coordinates = india.geometry.coordinates.flat(2);
const minX = Math.min(
	...coordinates.map(([longitude]) => (longitude * Math.PI) / 180),
);
const maxX = Math.max(
	...coordinates.map(([longitude]) => (longitude * Math.PI) / 180),
);
const minY = Math.min(...coordinates.map(([, latitude]) => mercator(latitude)));
const maxY = Math.max(...coordinates.map(([, latitude]) => mercator(latitude)));
const scale = Math.min(540 / (maxX - minX), 570 / (maxY - minY));
const left = (600 - (maxX - minX) * scale) / 2;
const top = (620 - (maxY - minY) * scale) / 2;
const project = ([longitude, latitude]) => [
	left + ((longitude * Math.PI) / 180 - minX) * scale,
	top + (maxY - mercator(latitude)) * scale,
];
const path = india.geometry.coordinates
	.map((polygon) =>
		polygon
			.map(
				(ring) =>
					ring
						.map(
							(coordinate, index) =>
								`${index ? "L" : "M"}${project(coordinate)
									.map((n) => n.toFixed(2))
									.join(",")}`,
						)
						.join("") + "Z",
			)
			.join(""),
	)
	.join("");
const output = `// Generated by scripts/build-landing-map.mjs. Natural Earth 1:50m, public domain.
// ${source}
// Mercator projection; mainland and all island polygons retained. De facto boundaries.
export const INDIA_OUTLINE = ${JSON.stringify(path)};
export const INDIA_PROJECTION = ${JSON.stringify({ minX, maxY, scale, left, top })} as const;
`;
await writeFile(
	new URL(
		"../apps/native/src/components/landing/india-geometry.ts",
		import.meta.url,
	),
	output,
);
console.log(
	`Generated India geometry: ${path.length} bytes; ${india.geometry.coordinates.length} polygons.`,
);
